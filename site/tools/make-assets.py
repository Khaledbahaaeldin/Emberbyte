#!/usr/bin/env python3
"""
Builds the generated assets of the website from the app's own sources, so the site never drifts from the app:

  * assets/fonts/roboto-flex.woff2   the app's Roboto Flex, subset to Latin (keeps the weight and width axes)
  * assets/screens/*.webp            the store screenshots, resized for the web
  * assets/themes.js                 the 12 themes (dark and light) read from the generated Kotlin palettes

Run from the repository root:  python site/tools/make-assets.py
Needs: pip install fonttools brotli pillow
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "site"
FONT_SRC = ROOT / "ui/design/src/main/res/font/roboto_flex.ttf"
SHOTS = ROOT / "fastlane/metadata/android/en-US/images/phoneScreenshots"
PALETTES = ROOT / "ui/design/src/main/kotlin/io/github/khaledbahaaeldin/emberbyte/ui/design/theme/palette/GeneratedPalettes.kt"

NAMES = {
    "dusk": "Dusk", "ember": "Ember", "monochrome": "Monochrome", "catppuccin": "Catppuccin", "gruvbox": "Gruvbox",
    "nord": "Nord", "rosepine": "Rosé Pine", "solarized": "Solarized", "dracula": "Dracula",
    "tokyonight": "Tokyo Night", "everforest": "Everforest", "kanagawa": "Kanagawa",
}
ROLES = ["background", "surface", "surface2", "text", "muted", "primary", "onPrimary", "accent", "onAccent",
         "warn", "onWarn", "danger", "onDanger", "track"]


def font():
    out = SITE / "assets/fonts/roboto-flex.woff2"
    unicodes = "U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2192,U+00B7,U+2713"
    subprocess.check_call([sys.executable, "-m", "fontTools.subset", str(FONT_SRC), f"--unicodes={unicodes}",
                           "--flavor=woff2", "--layout-features=*", f"--output-file={out}"])
    print("font", out.name, out.stat().st_size // 1024, "KB")


def screens():
    from PIL import Image
    for name in ["1_home", "2_apps", "3_plans", "4_plan_flow", "5_themes", "6_history", "7_app_detail"]:
        img = Image.open(SHOTS / f"{name}.png").convert("RGB")
        w = 640
        img = img.resize((w, round(img.height * w / img.width)), Image.LANCZOS)
        out = SITE / "assets/screens" / f"{name}.webp"
        img.save(out, "WEBP", quality=84, method=6)
        print("screen", out.name, out.stat().st_size // 1024, "KB")


def themes():
    text = PALETTES.read_text(encoding="utf-8")
    consts = {}
    for m in re.finditer(r"internal val (\w+) = EmberbytePalette\((.*?)\n\)", text, re.S):
        roles = dict(re.findall(r"(\w+) = Color\(0xFF([0-9A-Fa-f]{6})\)", m.group(2)))
        consts[m.group(1)] = {k: "#" + v.upper() for k, v in roles.items()}
    out = []
    for tid, name in NAMES.items():
        dark = consts[tid.capitalize() + "Dark"]
        light = consts[tid.capitalize() + "Light"]
        assert all(r in dark and r in light for r in ROLES), tid
        out.append({"id": tid, "name": name, "dark": dark, "light": light})
    js = "// GENERATED by site/tools/make-assets.py from the app's palettes. Do not edit.\nwindow.EMBERBYTE_THEMES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (SITE / "assets/themes.js").write_text(js, encoding="utf-8", newline="\n")
    print("themes", len(out))


if __name__ == "__main__":
    font()
    screens()
    themes()
